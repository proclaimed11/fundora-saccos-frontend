type AppIconName = keyof typeof icons

function isAppIconName(name: string): name is AppIconName {
  return Object.prototype.hasOwnProperty.call(icons, name)
}

type AppIconProps = {
  name: string
  className?: string
  size?: number
  strokeWidth?: number
}

export function AppIcon({ name, className, size = 16, strokeWidth = 2 }: AppIconProps) {
  if (!isAppIconName(name)) {
    throw new Error(`Unknown app icon: ${name}`)
  }
  const Icon = icons[name]

  return <Icon aria-hidden="true" className={className} size={size} strokeWidth={strokeWidth} />
}
